/**
 * Exports the ArcSLA ABI from the Foundry artifact.
 *
 *   forge build && bun run abi:export
 *
 * Writes:
 *   - contracts/abi/ArcSLA.abi.json   (plain JSON, for any tooling)
 *   - src/contracts/ArcSLA.abi.ts     (typed `as const` ABI for wagmi/viem)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const artifactPath = resolve(root, 'contracts/out/ArcSLA.sol/ArcSLA.json')

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as { abi: unknown[] }
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  throw new Error(`No ABI found in ${artifactPath}. Run "forge build" first.`)
}

const jsonPath = resolve(root, 'contracts/abi/ArcSLA.abi.json')
const tsPath = resolve(root, 'src/contracts/ArcSLA.abi.ts')
mkdirSync(dirname(jsonPath), { recursive: true })
mkdirSync(dirname(tsPath), { recursive: true })

writeFileSync(jsonPath, `${JSON.stringify(artifact.abi, null, 2)}\n`)
writeFileSync(
  tsPath,
  `// GENERATED by scripts/export-abi.ts from the Foundry artifact. Do not edit by hand.\n` +
    `export const arcSlaAbi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`,
)

console.log(`Exported ${artifact.abi.length} ABI entries -> ${jsonPath} and ${tsPath}`)
